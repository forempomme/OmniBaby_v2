// ------------------------------------------------------------------
// LMS -> valeur pour un Z donné
// ------------------------------------------------------------------
export function lmsValue(lms, z) {
  const [L, M, S] = lms;
  if (Math.abs(L) < 1e-6) return M * Math.exp(S * z);
  return M * Math.pow(1 + L * S * z, 1 / L);
}

// Récupère les coefficients LMS pour un âge en mois (clampé 0-36), avec
// interpolation linéaire entre mois entiers pour des âges fractionnaires.
export function getLMS(table, sexe, ageMonths) {
  const data = table[sexe === 'garcon' ? 'garcon' : 'fille'];
  const clamped = Math.max(0, Math.min(36, ageMonths));
  const lower = Math.floor(clamped);
  const upper = Math.ceil(clamped);
  if (lower === upper) return data[lower];
  const frac = clamped - lower;
  const a = data[lower];
  const b = data[upper];
  return [a[0] + (b[0] - a[0]) * frac, a[1] + (b[1] - a[1]) * frac, a[2] + (b[2] - a[2]) * frac];
}

// Estime le percentile (0-100) d'une valeur mesurée par recherche binaire
// sur le score Z (LMS inverse), puis conversion Z -> percentile via
// approximation de la fonction de répartition normale.
export function estimatePercentile(table, sexe, ageMonths, value) {
  const lms = getLMS(table, sexe, ageMonths);
  const [L, M, S] = lms;
  let z;
  if (Math.abs(L) < 1e-6) {
    z = Math.log(value / M) / S;
  } else {
    z = (Math.pow(value / M, L) - 1) / (L * S);
  }
  // Conversion Z -> percentile (approximation d'Abramowitz-Stegun)
  const p = 0.5 * (1 + erf(z / Math.SQRT2));
  return Math.round(Math.max(0, Math.min(100, p * 100)));
}

function erf(x) {
  // Approximation numérique de la fonction d'erreur
  const a1 = 0.254829592;
  const a2 = -0.284496736;
  const a3 = 1.421413741;
  const a4 = -1.453152027;
  const a5 = 1.061405429;
  const p = 0.3275911;
  const sign = x < 0 ? -1 : 1;
  const ax = Math.abs(x);
  const t = 1 / (1 + p * ax);
  const y = 1 - ((((a5 * t + a4) * t + a3) * t + a2) * t + a1) * t * Math.exp(-ax * ax);
  return sign * y;
}

