// value : nom d'icône, emoji d'interface, ou élément React déjà construit
export function UiIcon({ value, size = 20, className = '', ...rest }) {
  if (!value) return null;
  if (typeof value !== 'string') return value;
  const name = PATHS[value] ? value : EMOJI_ICON[value];
  if (!name) return <span className={className}>{value}</span>;
  const tone = ICON_TONE[name];
  return <Icon name={name} size={size} className={`${className} ${tone ? `ui-${tone}` : ''}`.trim()} {...rest} />;
}
